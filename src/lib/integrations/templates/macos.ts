/**
 * The macOS Finder Quick Action "Open in Overdeck" (PAN-5349 O-D13): an
 * Automator service bundle with one "Run Shell Script" action that runs the
 * absolute `pan` path for each selected file or folder.
 */
import { shellDoubleQuote } from './linux.js';

function xmlEscape(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/** The shell body: one `pan open` per selected item, passed as arguments. */
export function quickActionScript(panPath: string): string {
  return `for f in "$@"; do ${shellDoubleQuote(panPath)} open "$f"; done`;
}

