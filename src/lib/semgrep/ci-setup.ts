/**
 * PAN-4592: `pan semgrep ci-setup <project>` — open a pull request that adds
 * the Semgrep GitHub Actions workflow (ci-workflow.ts) to a project.
 *
 * It never pushes to the base branch and never touches the project's primary
 * checkout's working tree: it commits in a detached throwaway worktree under
 * `<OVERDECK_HOME>/tmp/semgrep-ci-setup/`, pushes by refspec to
 * `overdeck/semgrep-ci`, opens the pull request with `gh`, and removes the
 * worktree. The generated commit and push skip repository hooks
 * (`--no-verify`): the throwaway worktree has no installed dependencies, and
 * the pull request's CI and review gate the one generated file. Every refusal
 * is one line and runs nothing after it. See configuration/semgrep.mdx,
 * "CI workflow".
 */
import { execFile as execFileCb } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { promisify } from 'node:util';

import { resolveSastGateMode } from '../cloister/sast-gate.js';
import { loadConfigNoMigration } from '../config-yaml.js';
import type { NormalizedSemgrepConfig } from '../config-yaml/semgrep.js';
import { getOverdeckHome } from '../paths.js';
import { getProjectSync, type ProjectConfig } from '../projects.js';
import { getRepoTargetBranch } from '../project-repos.js';
import {
  ciGateForMode,
  renderSemgrepWorkflow,
  SEMGREP_WORKFLOW_PATH,
  validateBaseBranch,
  validateCiConfigs,
  type SemgrepCiGate,
} from './ci-workflow.js';

const execFileAsync = promisify(execFileCb);

export const SEMGREP_SETUP_BRANCH = 'overdeck/semgrep-ci';

const READ_TIMEOUT_MS = 30_000;
const NETWORK_TIMEOUT_MS = 120_000;

export interface SemgrepCiSetupOptions {
  projectKey: string;
  sarifUpload?: boolean;
  dryRun?: boolean;
}

export interface SemgrepCiSetupDeps {
  loadSemgrepConfig: () => Promise<NormalizedSemgrepConfig>;
  getProject: (key: string) => ProjectConfig | null;
  /** Rejects with an error that carries the command's `stderr`. */
  run: (file: 'git' | 'gh', args: string[], opts: { cwd?: string; timeoutMs: number }) => Promise<{ stdout: string; stderr: string }>;
  writeFile: (path: string, content: string) => Promise<void>;
  mkdirp: (path: string) => Promise<void>;
  tmpRoot: () => string;
  now: () => number;
  log: (line: string) => void;
}

export type SemgrepCiSetupResult =
  | { ok: true; prUrl: string | null; existing: boolean; dryRun: boolean }
  | { ok: false; message: string };

const defaultDeps: SemgrepCiSetupDeps = {
  loadSemgrepConfig: async () => (await loadConfigNoMigration()).config.security.semgrep,
  getProject: getProjectSync,
  run: async (file, args, opts) => {
    const { stdout, stderr } = await execFileAsync(file, args, {
      ...(opts.cwd ? { cwd: opts.cwd } : {}),
      timeout: opts.timeoutMs,
      encoding: 'utf-8',
      // pan's own git operations pass the agent git guard (it refuses commits on a detached HEAD).
      env: { ...process.env, OVERDECK_PAN_GIT_OP: '1' },
    });
    return { stdout, stderr };
  },
  writeFile: (path, content) => writeFile(path, content, 'utf-8'),
  mkdirp: async (path) => { await mkdir(path, { recursive: true }); },
  tmpRoot: () => join(getOverdeckHome(), 'tmp', 'semgrep-ci-setup'),
  now: () => Date.now(),
  log: (line) => console.log(line),
};

/** The full stderr of a failed command, or its message. */
function stderrOf(err: unknown): string {
  const stderr = (err as { stderr?: unknown } | null)?.stderr;
  if (typeof stderr === 'string' && stderr.trim()) return stderr;
  return err instanceof Error ? err.message : String(err);
}

/** The first non-empty line of a failed command's stderr, or its message. */
function firstStderrLine(err: unknown): string {
  return stderrOf(err).split('\n').map((line) => line.trim()).find(Boolean) ?? 'unknown error';
}

const WORKFLOW_SCOPE_PATTERN = /workflow.{0,40}scope|refusing to allow an OAuth App to create or update workflow/i;

function pushFailureMessage(err: unknown, projectKey: string): string {
  if (WORKFLOW_SCOPE_PATTERN.test(stderrOf(err))) {
    return 'GitHub refused the push: the credential for origin lacks the "workflow" scope. '
      + 'Run "gh auth refresh -s workflow" (HTTPS remotes) or push over SSH, '
      + `then run pan semgrep ci-setup ${projectKey} again.`;
  }
  return `git push failed: ${firstStderrLine(err)}`;
}

function prBody(configs: readonly string[], gate: SemgrepCiGate, sarifUpload: boolean): string {
  const gateLine = gate === 'blocking'
    ? 'Gate: `blocking` — a pull request that adds a Semgrep finding fails the semgrep check.'
    : 'Gate: `advisory` — the semgrep check never fails; findings show as warnings.';
  return [
    `This pull request adds \`${SEMGREP_WORKFLOW_PATH}\`, generated by \`pan semgrep ci-setup\` (Overdeck).`,
    '',
    `Configs: ${configs.map((config) => `\`${config}\``).join(', ')}`,
    gateLine,
    'To change the gate later, edit the `OVERDECK_SEMGREP_GATE` line in the workflow (`blocking` or `advisory`).',
    '',
    'Pull requests are scanned diff-aware: only findings on code the pull request adds are reported.',
    sarifUpload
      ? 'SARIF upload is on: pushes to the base branch are scanned and the results go to GitHub code scanning; those runs never fail.'
      : 'SARIF upload is off.',
    '',
    'The commit was made in a throwaway worktree and skipped repository hooks (`--no-verify`); this pull request\'s CI and review gate it.',
  ].join('\n');
}

export async function runSemgrepCiSetup(
  opts: SemgrepCiSetupOptions,
  overrides: Partial<SemgrepCiSetupDeps> = {},
): Promise<SemgrepCiSetupResult> {
  const deps: SemgrepCiSetupDeps = { ...defaultDeps, ...overrides };
  const key = opts.projectKey;
  const sarifUpload = opts.sarifUpload === true;
  const refuse = (message: string): SemgrepCiSetupResult => ({ ok: false, message });

  // 1. Semgrep must be on.
  const cfg = await deps.loadSemgrepConfig();
  if (cfg.enabled !== true) {
    return refuse('Semgrep support is off (security.semgrep.enabled: false in ~/.overdeck/config.yaml). Turn it on first.');
  }

  // 2. A single-repo GitHub project.
  const project = deps.getProject(key);
  if (!project) return refuse(`Unknown project "${key}". Run: pan project list`);
  const githubRepo = project.github_repo;
  if (!githubRepo) return refuse(`Project ${key} has no github_repo; pan semgrep ci-setup supports GitHub repositories only.`);
  if ((project.workspace?.repos?.length ?? 0) > 0) {
    return refuse(`Project ${key} is a polyrepo project; pan semgrep ci-setup supports single-repo projects only.`);
  }

  // 3. Only validated values are written into the workflow.
  const configsInvalid = validateCiConfigs(cfg.configs);
  if (configsInvalid) return refuse(configsInvalid);

  // 4. The gate mode, resolved once.
  const decision = resolveSastGateMode(cfg, project.verification?.sast, deps.log);
  const gate = ciGateForMode(decision.mode);

  // 5. The branch pull requests target.
  const configuredBase = project.workspace?.pr_target || project.workspace?.default_branch
    ? getRepoTargetBranch(undefined, project)
    : null;
  let base: string;
  if (configuredBase) {
    base = configuredBase;
  } else if (opts.dryRun) {
    base = 'main';
    deps.log('(no base branch configured; a real run reads origin/HEAD)');
  } else {
    let originHead = '';
    try {
      originHead = (await deps.run('git', ['symbolic-ref', '--short', 'refs/remotes/origin/HEAD'], { cwd: project.path, timeoutMs: READ_TIMEOUT_MS })).stdout.trim();
    } catch { /* no origin/HEAD: fall back to main */ }
    base = originHead.replace(/^origin\//, '') || 'main';
  }
  const baseInvalid = validateBaseBranch(base);
  if (baseInvalid) return refuse(baseInvalid);

  const workflow = renderSemgrepWorkflow({ configs: cfg.configs, baseBranch: base, gate, severity: cfg.severity, sarifUpload });

  // 6. Dry run: show the target and the file, change nothing.
  if (opts.dryRun) {
    deps.log(`Repository: ${githubRepo}`);
    deps.log(`Base branch: ${base}`);
    deps.log(`Branch: ${SEMGREP_SETUP_BRANCH}`);
    deps.log(`File: ${SEMGREP_WORKFLOW_PATH}`);
    deps.log(`Gate: ${gate} (${decision.reason})`);
    deps.log(workflow);
    return { ok: true, prUrl: null, existing: false, dryRun: true };
  }

  const read = (args: string[]) => deps.run('git', args, { cwd: project.path, timeoutMs: READ_TIMEOUT_MS });

  // 7. origin must be github_repo: the branch goes to origin, the pull request to github_repo.
  let originUrl: string;
  try {
    originUrl = (await read(['remote', 'get-url', 'origin'])).stdout.trim();
  } catch (err) {
    return refuse(`git remote get-url origin failed: ${firstStderrLine(err)}`);
  }
  const normalizedOrigin = originUrl.toLowerCase().replace(/\.git$/, '');
  const repoLower = githubRepo.toLowerCase();
  if (!normalizedOrigin.endsWith(`/${repoLower}`) && !normalizedOrigin.endsWith(`:${repoLower}`)) {
    return refuse(`origin of ${project.path} is ${originUrl}, not ${githubRepo}; ci-setup pushes to origin and opens the pull request there.`);
  }

  // 8. The current base branch.
  try {
    await deps.run('git', ['fetch', 'origin', base], { cwd: project.path, timeoutMs: NETWORK_TIMEOUT_MS });
  } catch (err) {
    return refuse(`git fetch origin ${base} failed: ${firstStderrLine(err)}`);
  }

  // 9. Never overwrite an existing workflow.
  let workflowExists = false;
  try {
    await read(['cat-file', '-e', `origin/${base}:${SEMGREP_WORKFLOW_PATH}`]);
    workflowExists = true;
  } catch { /* absent: the expected case */ }
  if (workflowExists) return refuse(`${githubRepo} already has ${SEMGREP_WORKFLOW_PATH} on ${base}; ci-setup never overwrites it.`);

  // 10. An open pull request from the setup branch is success.
  let openPrs: Array<{ url?: string }>;
  try {
    const { stdout } = await deps.run('gh', ['pr', 'list', '--repo', githubRepo, '--head', SEMGREP_SETUP_BRANCH, '--state', 'open', '--json', 'url', '--limit', '1'], { timeoutMs: READ_TIMEOUT_MS });
    openPrs = JSON.parse(stdout.trim() || '[]') as Array<{ url?: string }>;
  } catch (err) {
    return refuse(`gh pr list failed: ${firstStderrLine(err)}`);
  }
  const openUrl = openPrs.find((pr) => typeof pr.url === 'string' && pr.url)?.url;
  if (openUrl) {
    deps.log(`A pull request from ${SEMGREP_SETUP_BRANCH} is already open: ${openUrl}`);
    return { ok: true, prUrl: openUrl, existing: true, dryRun: false };
  }

  // 11. A leftover setup branch with no open pull request.
  let remoteBranch: string;
  try {
    remoteBranch = (await read(['ls-remote', '--heads', 'origin', SEMGREP_SETUP_BRANCH])).stdout.trim();
  } catch (err) {
    return refuse(`git ls-remote failed: ${firstStderrLine(err)}`);
  }
  if (remoteBranch) {
    return refuse(`Branch ${SEMGREP_SETUP_BRANCH} already exists on origin with no open pull request. Delete it or open a pull request from it.`);
  }

  // 12. A detached throwaway worktree off origin/<base>.
  const root = deps.tmpRoot();
  const path = join(root, `${key}-${deps.now()}`);
  try {
    await deps.mkdirp(root);
    await deps.run('git', ['worktree', 'add', '--detach', path, `origin/${base}`], { cwd: project.path, timeoutMs: READ_TIMEOUT_MS });
  } catch (err) {
    return refuse(`git worktree add failed: ${firstStderrLine(err)}`);
  }

  // 13. Commit, push by refspec, open the pull request; always remove the worktree.
  let prUrl: string;
  try {
    await deps.mkdirp(join(path, '.github', 'workflows'));
    await deps.writeFile(join(path, SEMGREP_WORKFLOW_PATH), workflow);
    const inWorktree = (args: string[], timeoutMs = READ_TIMEOUT_MS) => deps.run('git', args, { cwd: path, timeoutMs });
    try {
      await inWorktree(['add', SEMGREP_WORKFLOW_PATH]);
      await inWorktree(['commit', '--no-verify', '-m', 'ci: add semgrep workflow', '-m', 'Generated by pan semgrep ci-setup.']);
    } catch (err) {
      return refuse(`git commit failed: ${firstStderrLine(err)}`);
    }
    try {
      await inWorktree(['push', '--no-verify', 'origin', `HEAD:refs/heads/${SEMGREP_SETUP_BRANCH}`], NETWORK_TIMEOUT_MS);
    } catch (err) {
      return refuse(pushFailureMessage(err, key));
    }
    try {
      const { stdout } = await deps.run('gh', [
        'pr', 'create', '--repo', githubRepo, '--base', base, '--head', SEMGREP_SETUP_BRANCH,
        '--title', 'ci: add Semgrep workflow', '--body', prBody(cfg.configs, gate, sarifUpload),
      ], { cwd: path, timeoutMs: NETWORK_TIMEOUT_MS });
      prUrl = stdout.split('\n').map((line) => line.trim()).filter(Boolean).at(-1) ?? '';
    } catch (err) {
      return refuse(`gh pr create failed: ${firstStderrLine(err)}`);
    }
  } catch (err) {
    return refuse(`Could not write ${SEMGREP_WORKFLOW_PATH}: ${err instanceof Error ? err.message : String(err)}`);
  } finally {
    try {
      await deps.run('git', ['worktree', 'remove', '--force', path], { cwd: project.path, timeoutMs: READ_TIMEOUT_MS });
    } catch (err) {
      deps.log(`Warning: could not remove the worktree ${path}: ${firstStderrLine(err)}`);
    }
  }

  // 14.
  return { ok: true, prUrl: prUrl || null, existing: false, dryRun: false };
}
