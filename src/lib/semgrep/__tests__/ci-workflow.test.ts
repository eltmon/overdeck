import { describe, expect, it } from 'vitest';
import { parse } from 'yaml';

import {
  ciGateForMode,
  renderSemgrepWorkflow,
  SEMGREP_WORKFLOW_PATH,
  validateBaseBranch,
  validateCiConfigs,
  type SemgrepWorkflowOptions,
} from '../ci-workflow.js';

const EXAMPLE: SemgrepWorkflowOptions = {
  configs: ['p/default', '.semgrep/'],
  baseBranch: 'main',
  gate: 'advisory',
  severity: 'ERROR',
  sarifUpload: false,
  version: '1.180.0',
};

/** The PAN-4592 PRD WI-3 example, verbatim. */
const EXPECTED = `# Generated by \`pan semgrep ci-setup\` (Overdeck). You may edit this file; Overdeck never rewrites it.
# Pull requests are scanned diff-aware: only findings on code the pull request adds are reported.
# OVERDECK_SEMGREP_GATE: blocking fails the job on a new finding; advisory only warns.
name: semgrep

on:
  pull_request: {}

permissions:
  contents: read

jobs:
  semgrep:
    name: semgrep
    runs-on: ubuntu-latest
    container:
      image: semgrep/semgrep:1.180.0
    env:
      OVERDECK_SEMGREP_GATE: advisory
      SEMGREP_ENABLE_VERSION_CHECK: "0"
      SEMGREP_SEND_METRICS: "off"
      BASE_REF: \${{ github.base_ref }}
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - name: semgrep scan
        run: |
          git config --global --add safe.directory "$GITHUB_WORKSPACE"
          scan() {
            if [ -n "$BASE_REF" ]; then
              base_sha=$(git merge-base "origin/$BASE_REF" HEAD) || return $?
              semgrep scan --config p/default --config .semgrep/ --severity ERROR --sarif-output=semgrep.sarif --metrics off --error --baseline-commit "$base_sha"
            else
              semgrep scan --config p/default --config .semgrep/ --severity ERROR --sarif-output=semgrep.sarif --metrics off
            fi
          }
          status=0
          scan || status=$?
          if [ "$status" -ne 0 ] && [ "$OVERDECK_SEMGREP_GATE" = "blocking" ] && [ -n "$BASE_REF" ]; then
            exit "$status"
          fi
          [ "$status" -eq 0 ] || echo "::warning title=semgrep::semgrep exited with status $status; this run does not fail (gate $OVERDECK_SEMGREP_GATE, or not a pull request)"
`;

interface Workflow {
  on: Record<string, unknown> & { push?: { branches: string[] } };
  permissions: Record<string, string>;
  jobs: {
    semgrep: Record<string, unknown> & {
      container: { image: string };
      env: Record<string, string>;
      steps: Array<Record<string, unknown> & { run?: string; uses?: string }>;
    };
  };
}

const parsed = (text: string) => parse(text) as Workflow;
const runScript = (workflow: Workflow) => workflow.jobs.semgrep.steps.find((step) => step.name === 'semgrep scan')!.run!;
const scanLines = (text: string) => text.split('\n').filter((line) => line.trim().startsWith('semgrep scan'));

describe('renderSemgrepWorkflow (PAN-4592)', () => {
  it('writes the workflow path under .github/workflows', () => {
    expect(SEMGREP_WORKFLOW_PATH).toBe('.github/workflows/semgrep.yml');
  });

  it('renders the PRD example exactly', () => {
    expect(renderSemgrepWorkflow(EXAMPLE)).toBe(EXPECTED);
  });

  it('parses to a pinned, read-only, pull-request-only, diff-aware scan', () => {
    const workflow = parsed(renderSemgrepWorkflow(EXAMPLE));

    expect(workflow.jobs.semgrep.container.image).toBe('semgrep/semgrep:1.180.0');
    expect(workflow.permissions).toEqual({ contents: 'read' });
    expect(Object.keys(workflow.on)).toEqual(['pull_request']);
    expect(workflow.jobs.semgrep).not.toHaveProperty('if');
    expect(workflow.jobs.semgrep.env).toMatchObject({ SEMGREP_ENABLE_VERSION_CHECK: '0', SEMGREP_SEND_METRICS: 'off', BASE_REF: '${{ github.base_ref }}' });
    const run = runScript(workflow);
    for (const fragment of ['--metrics off', '--error', '--sarif-output=semgrep.sarif', '--baseline-commit', '--severity ERROR']) {
      expect(run).toContain(fragment);
    }
    expect(run).not.toContain('${{');
  });

  it('defaults the image tag to the managed Semgrep version', () => {
    const { version: _version, ...options } = EXAMPLE;
    expect(parsed(renderSemgrepWorkflow(options)).jobs.semgrep.container.image).toBe('semgrep/semgrep:1.180.0');
  });

  it('maps the severity threshold to --severity flags on both scan lines', () => {
    const warning = scanLines(renderSemgrepWorkflow({ ...EXAMPLE, severity: 'WARNING' }));
    expect(warning).toHaveLength(2);
    for (const line of warning) expect(line).toContain('--severity WARNING --severity ERROR');

    const info = renderSemgrepWorkflow({ ...EXAMPLE, severity: 'INFO' });
    expect(scanLines(info)).toHaveLength(2);
    expect(info).not.toContain('--severity');
    expect(info).toContain('--config .semgrep/ --sarif-output=semgrep.sarif');
  });

  it('changes only the gate line for gate blocking', () => {
    const advisory = renderSemgrepWorkflow(EXAMPLE).split('\n');
    const blockingText = renderSemgrepWorkflow({ ...EXAMPLE, gate: 'blocking' });
    const blocking = blockingText.split('\n');

    expect(parsed(blockingText).jobs.semgrep.env.OVERDECK_SEMGREP_GATE).toBe('blocking');
    expect(blocking).toHaveLength(advisory.length);
    const changed = blocking.flatMap((line, index) => (line === advisory[index] ? [] : [[advisory[index], line]]));
    expect(changed).toEqual([['      OVERDECK_SEMGREP_GATE: advisory', '      OVERDECK_SEMGREP_GATE: blocking']]);
  });

  it('adds the push trigger, code-scanning permissions and a non-fatal upload step with sarifUpload', () => {
    const text = renderSemgrepWorkflow({ ...EXAMPLE, sarifUpload: true });
    const workflow = parsed(text);

    expect(workflow.on.push!.branches).toEqual(['main']);
    expect(workflow.permissions).toEqual({ contents: 'read', 'security-events': 'write', actions: 'read' });
    const upload = workflow.jobs.semgrep.steps.find((step) => step.uses === 'github/codeql-action/upload-sarif@v3');
    expect(upload).toMatchObject({ 'continue-on-error': true, with: { sarif_file: 'semgrep.sarif' } });
    expect(text).toContain('Pushes to main are scanned for GitHub code scanning and never fail.');
  });

  it('writes the push branch quoted', () => {
    const text = renderSemgrepWorkflow({ ...EXAMPLE, baseBranch: 'release/1.2', sarifUpload: true });
    expect(text).toContain('    branches: ["release/1.2"]');
    expect(parsed(text).on.push!.branches).toEqual(['release/1.2']);
  });

  it('throws on input that fails validation', () => {
    expect(() => renderSemgrepWorkflow({ ...EXAMPLE, configs: ['auto'] })).toThrow(/auto/);
    expect(() => renderSemgrepWorkflow({ ...EXAMPLE, baseBranch: 'main;x' })).toThrow(/base branch/);
    expect(() => renderSemgrepWorkflow({ ...EXAMPLE, version: '1.0 ; x' })).toThrow(/version/);
  });
});

describe('validateCiConfigs (PAN-4592)', () => {
  it('rejects auto, absolute, flag-like, shell-unsafe and parent-directory entries, and an empty list', () => {
    expect(validateCiConfigs(['auto'])).toBe('security.semgrep.configs entry "auto" cannot be used in CI: --config auto needs metrics, which Overdeck turns off');
    expect(validateCiConfigs(['/abs/rules.yml'])).toBe('security.semgrep.configs entry "/abs/rules.yml" is not a registry id or a repo-relative path');
    for (const config of ['--config', 'p/default;rm -rf x', '../rules', 'rules/../../x']) {
      expect(validateCiConfigs([config]), config).toContain(`entry "${config}"`);
    }
    expect(validateCiConfigs(['p/default', 'auto'])).toContain('"auto"');
    expect(validateCiConfigs([])).not.toBeNull();
  });

  it('accepts registry ids and repo-relative paths', () => {
    expect(validateCiConfigs(['p/default', 'r/python.lang.security', '.semgrep/', 'rules/custom.yml'])).toBeNull();
  });
});

describe('validateBaseBranch (PAN-4592)', () => {
  it('rejects shell metacharacters and accepts a slash-separated branch', () => {
    expect(validateBaseBranch('main;x')).toBe('base branch "main;x" has characters ci-setup does not write into a workflow');
    expect(validateBaseBranch('$(x)')).not.toBeNull();
    expect(validateBaseBranch('release/1.2')).toBeNull();
  });
});

describe('ciGateForMode (PAN-4592)', () => {
  it('keeps blocking and maps advisory and off to advisory', () => {
    expect(ciGateForMode('blocking')).toBe('blocking');
    expect(ciGateForMode('advisory')).toBe('advisory');
    expect(ciGateForMode('off')).toBe('advisory');
  });
});
