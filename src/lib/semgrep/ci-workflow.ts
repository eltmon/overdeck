/**
 * PAN-4592: the Semgrep GitHub Actions workflow `pan semgrep ci-setup` adds to
 * a project, and the checks on the values written into it.
 *
 * Pure: no I/O. The workflow runs the pinned `semgrep/semgrep` image, scans a
 * pull request diff-aware (`--baseline-commit` at the merge base), and carries
 * the gate mode in its `OVERDECK_SEMGREP_GATE` env line: `blocking` fails the
 * job on a new finding, `advisory` only warns, so an advisory check concludes
 * green for every merge-verdict reader. Only the `--config` values and the
 * base branch are interpolated, and only after `validateCiConfigs` and
 * `validateBaseBranch` accept them. See configuration/semgrep.mdx, "CI workflow".
 */
import type { SemgrepGateMode, SemgrepSeverity } from '../config-yaml/semgrep.js';
import { SEMGREP_VERSION } from './install.js';

export const SEMGREP_WORKFLOW_PATH = '.github/workflows/semgrep.yml';

export type SemgrepCiGate = 'blocking' | 'advisory';

export interface SemgrepWorkflowOptions {
  configs: readonly string[];
  baseBranch: string;
  gate: SemgrepCiGate;
  /** `security.semgrep.severity`; mapped to `--severity` flags. */
  severity: SemgrepSeverity;
  sarifUpload: boolean;
  /** Defaults to SEMGREP_VERSION. */
  version?: string;
}

const CONFIG_PATTERN = /^[A-Za-z0-9._][A-Za-z0-9._/@:+-]*$/;
const BASE_BRANCH_PATTERN = /^[A-Za-z0-9._/-]+$/;
const VERSION_PATTERN = /^[A-Za-z0-9._-]+$/;

/** Null when valid, else the one-line refusal reason. */
export function validateCiConfigs(configs: readonly string[]): string | null {
  if (configs.length === 0) return 'security.semgrep.configs is empty; the workflow needs at least one --config';
  for (const config of configs) {
    if (config === 'auto') {
      return `security.semgrep.configs entry "auto" cannot be used in CI: --config auto needs metrics, which Overdeck turns off`;
    }
    if (!CONFIG_PATTERN.test(config) || config.split('/').includes('..')) {
      return `security.semgrep.configs entry "${config}" is not a registry id or a repo-relative path`;
    }
  }
  return null;
}

/** Null when valid, else the one-line refusal reason. */
export function validateBaseBranch(branch: string): string | null {
  return BASE_BRANCH_PATTERN.test(branch) ? null : `base branch "${branch}" has characters ci-setup does not write into a workflow`;
}

/** `blocking` stays blocking; `advisory` and `off` become `advisory`. */
export function ciGateForMode(mode: SemgrepGateMode): SemgrepCiGate {
  return mode === 'blocking' ? 'blocking' : 'advisory';
}

/** The `--severity` flags that report findings at `severity` or above. */
function severityFlags(severity: SemgrepSeverity): string[] {
  if (severity === 'ERROR') return ['--severity', 'ERROR'];
  if (severity === 'WARNING') return ['--severity', 'WARNING', '--severity', 'ERROR'];
  return [];
}

/** Throws on input that fails validation; callers validate first. */
export function renderSemgrepWorkflow(opts: SemgrepWorkflowOptions): string {
  const version = opts.version ?? SEMGREP_VERSION;
  const invalid = validateCiConfigs(opts.configs)
    ?? validateBaseBranch(opts.baseBranch)
    ?? (VERSION_PATTERN.test(version) ? null : `Semgrep version "${version}" is not a valid image tag`);
  if (invalid) throw new Error(invalid);

  const scan = [
    'semgrep scan',
    ...opts.configs.map((config) => `--config ${config}`),
    ...severityFlags(opts.severity),
    '--sarif-output=semgrep.sarif',
    '--metrics off',
  ].join(' ');
  const gateComment = '# OVERDECK_SEMGREP_GATE: blocking fails the job on a new finding; advisory only warns.'
    + (opts.sarifUpload ? ` Pushes to ${opts.baseBranch} are scanned for GitHub code scanning and never fail.` : '');
  const on = opts.sarifUpload
    ? ['  pull_request: {}', '  push:', `    branches: [${JSON.stringify(opts.baseBranch)}]`]
    : ['  pull_request: {}'];
  const permissions = opts.sarifUpload
    ? ['  contents: read', '  security-events: write', '  actions: read']
    : ['  contents: read'];
  const upload = opts.sarifUpload
    ? [
      '      - name: Upload SARIF to code scanning',
      "        if: always() && hashFiles('semgrep.sarif') != ''",
      '        continue-on-error: true',
      '        uses: github/codeql-action/upload-sarif@v3',
      '        with:',
      '          sarif_file: semgrep.sarif',
    ]
    : [];

  return [
    '# Generated by `pan semgrep ci-setup` (Overdeck). You may edit this file; Overdeck never rewrites it.',
    '# Pull requests are scanned diff-aware: only findings on code the pull request adds are reported.',
    gateComment,
    'name: semgrep',
    '',
    'on:',
    ...on,
    '',
    'permissions:',
    ...permissions,
    '',
    'jobs:',
    '  semgrep:',
    '    name: semgrep',
    '    runs-on: ubuntu-latest',
    '    container:',
    `      image: semgrep/semgrep:${version}`,
    '    env:',
    `      OVERDECK_SEMGREP_GATE: ${opts.gate}`,
    '      SEMGREP_ENABLE_VERSION_CHECK: "0"',
    '      SEMGREP_SEND_METRICS: "off"',
    '      BASE_REF: ${{ github.base_ref }}',
    '    steps:',
    '      - uses: actions/checkout@v4',
    '        with:',
    '          fetch-depth: 0',
    '      - name: semgrep scan',
    '        run: |',
    '          git config --global --add safe.directory "$GITHUB_WORKSPACE"',
    '          scan() {',
    '            if [ -n "$BASE_REF" ]; then',
    '              base_sha=$(git merge-base "origin/$BASE_REF" HEAD) || return $?',
    `              ${scan} --error --baseline-commit "$base_sha"`,
    '            else',
    `              ${scan}`,
    '            fi',
    '          }',
    '          status=0',
    '          scan || status=$?',
    '          if [ "$status" -ne 0 ] && [ "$OVERDECK_SEMGREP_GATE" = "blocking" ] && [ -n "$BASE_REF" ]; then',
    '            exit "$status"',
    '          fi',
    '          [ "$status" -eq 0 ] || echo "::warning title=semgrep::semgrep exited with status $status; this run does not fail (gate $OVERDECK_SEMGREP_GATE, or not a pull request)"',
    ...upload,
    '',
  ].join('\n');
}
