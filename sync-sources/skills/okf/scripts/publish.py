#!/usr/bin/env python3
"""Publish an OKF bundle's public concepts as a static site, or check it for redaction matches."""

from __future__ import annotations

import argparse
from dataclasses import replace
from pathlib import Path
import shutil
import sys

from okf_common import markdown_links
from publish_markdown import visible_text
from publish_model import Finding, PublishConcept, PublishModel, Source, build_model
from publish_redact import PROFILE_FILENAME, Profile, load_profile, redact, scan
from publish_render import filter_index_markdown, kept_index_lines, render_site, site_title
from publish_search import write_search

MARKER = ".okf-publish"
MARKER_TEXT = "Generated by OKF publish.py. Every run deletes and rebuilds this directory.\n"


def _location_key(finding: Finding) -> tuple[str, int, str, str]:
    path, _, line = finding.location.rpartition(":")
    if path and line.isdigit():
        return (path, int(line), finding.code, finding.message)
    return (finding.location, 0, finding.code, finding.message)


def _rule_ids(text: str, profile: Profile) -> list[str]:
    return sorted({rule_id for rule_id, _line in scan(text, profile)})


def id_findings(model: PublishModel, profile: Profile) -> list[Finding]:
    """Rules that match a public concept ID or a published directory path (URLs cannot be redacted)."""
    findings: list[Finding] = []
    for concept_id in model.public_ids():
        for rule_id in _rule_ids(concept_id, profile):
            findings.append(
                Finding(
                    "P_ID_REDACTION",
                    model.concepts[concept_id].path,
                    f"rule {rule_id} matches the concept ID; rename the concept or make it private",
                )
            )
    for directory in sorted(model.public_dirs()):
        if not directory:
            continue
        for rule_id in _rule_ids(directory, profile):
            findings.append(
                Finding(
                    "P_ID_REDACTION",
                    f"{directory}/",
                    f"rule {rule_id} matches the directory path; rename the directory or make its concepts private",
                )
            )
    return findings


def out_findings(out: Path, bundle: Path, shown: str) -> list[Finding]:
    """Refuse an --out that is the bundle, an ancestor of it, a file, or an unmarked non-empty directory."""
    if out == bundle or out in bundle.parents:
        return [Finding("P_OUT_UNSAFE", shown, "--out is the bundle root or an ancestor of it")]
    if out.exists() and not out.is_dir():
        return [Finding("P_OUT_UNSAFE", shown, "--out exists and is not a directory")]
    if out.is_dir() and any(out.iterdir()) and not (out / MARKER).is_file():
        return [
            Finding(
                "P_OUT_UNSAFE",
                shown,
                f"--out is a non-empty directory without {MARKER}; refusing to delete its contents",
            )
        ]
    return []


def prepare_out(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    if (out / MARKER).is_file():
        for entry in sorted(out.iterdir()):
            if entry.is_dir() and not entry.is_symlink():
                shutil.rmtree(entry)
            else:
                entry.unlink()
    with (out / MARKER).open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(MARKER_TEXT)


def _redact_concept(concept: PublishConcept, profile: Profile, counts: list[int]) -> PublishConcept:
    def clean(text: str) -> str:
        new_text, fired = redact(text, profile)
        counts.append(sum(fired.values()))
        return new_text

    body = clean(concept.body)
    return replace(
        concept,
        title=clean(concept.title),
        description=clean(concept.description),
        type=clean(concept.type),
        status=clean(concept.status),
        tags=tuple(clean(tag) for tag in concept.tags),
        sources=tuple(Source(clean(s.title), clean(s.resource), clean(s.author)) for s in concept.sources),
        body=body,
        links=tuple(markdown_links(body)),
    )


def redacted_copies(
    model: PublishModel, index_texts: dict[str, str], profile: Profile
) -> tuple[PublishModel, dict[str, str], int]:
    counts: list[int] = []
    concepts = {
        concept_id: _redact_concept(concept, profile, counts) if concept.visibility == "public" else concept
        for concept_id, concept in model.concepts.items()
    }
    texts: dict[str, str] = {}
    for directory, text in index_texts.items():
        texts[directory], fired = redact(text, profile)
        counts.append(sum(fired.values()))
    return replace(model, concepts=concepts), texts, sum(counts)


def _field_findings(location: str, field: str, text: str, profile: Profile) -> list[Finding]:
    return [
        Finding("P_REDACTION", location, f"rule {rule_id} matches published text (field {field})")
        for rule_id in _rule_ids(text, profile)
    ]


def _visible_hits(lines: list[str], profile: Profile) -> list[tuple[str, int]]:
    """Scan each line as a reader sees it, so Markdown escapes, emphasis or link syntax cannot split a match."""
    hits: list[tuple[str, int]] = []
    for number, line in enumerate(lines, start=1):
        hits.extend((rule_id, number) for rule_id, _line in scan(visible_text(line), profile))
    return hits


def check_findings(model: PublishModel, profile: Profile) -> list[Finding]:
    """Scan the published text of public concepts and published index pages (``--check``)."""
    findings: set[Finding] = set()
    for concept_id in model.public_ids():
        concept = model.concepts[concept_id]
        fields = [
            ("title", concept.title),
            ("description", concept.description),
            ("type", concept.type),
            ("status", concept.status),
        ]
        fields.extend(("tags", tag) for tag in concept.tags)
        for source in concept.sources:
            fields.extend(
                [("sources.title", source.title), ("sources.resource", source.resource), ("sources.author", source.author)]
            )
        for field, text in fields:
            findings.update(_field_findings(concept.path, field, text, profile))
        for rule_id, line in scan(concept.body, profile) + _visible_hits(concept.body.split("\n"), profile):
            findings.add(
                Finding(
                    "P_REDACTION",
                    f"{concept.path}:{concept.body_start_line + line - 1}",
                    f"rule {rule_id} matches published text (field body)",
                )
            )

    public_dirs = model.public_dirs()
    for directory, text in sorted(model.index_files.items()):
        if directory not in public_dirs:
            continue
        kept = kept_index_lines(text, directory, model)
        filtered = "\n".join(line for _number, line in kept)
        index_path = f"{directory}/index.md" if directory else "index.md"
        offset = model.index_offsets.get(directory, 0)
        hits = scan(filtered, profile) + _visible_hits([text_line for _number, text_line in kept], profile)
        for rule_id, line in hits:
            file_line = kept[line - 1][0] + offset
            findings.add(
                Finding("P_REDACTION", f"{index_path}:{file_line}", f"rule {rule_id} matches published text (field index)")
            )
    return list(findings)


def _print_findings(findings: list[Finding]) -> None:
    for finding in sorted(findings, key=_location_key):
        print(finding.line())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Publish an OKF bundle's public concepts as a static site.")
    parser.add_argument("--bundle", default=".", help="bundle root directory (default: current directory)")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--out", help="output directory for the static site")
    mode.add_argument("--check", action="store_true", help="scan public text for redaction matches; write nothing")
    parser.add_argument("--profile", help=f"redaction profile (default: <bundle>/{PROFILE_FILENAME} when present)")
    args = parser.parse_args(argv)

    bundle = Path(args.bundle).resolve()
    if not bundle.is_dir():
        print(Finding("P_BUNDLE_MISSING", args.bundle, "bundle directory not found").line())
        return 2

    profile_path = Path(args.profile).resolve() if args.profile else None
    profile, errors = load_profile(bundle, profile_path)
    if profile is None:
        shown = args.profile if args.profile else PROFILE_FILENAME
        for error in errors:
            print(Finding("P_PROFILE_INVALID", shown, error).line())
        return 2

    out = Path(args.out).resolve() if args.out else None
    model, findings = build_model(bundle, exclude=out)
    findings.extend(id_findings(model, profile))
    public_dirs = model.public_dirs()
    filtered = {d: filter_index_markdown(t, d, model) for d, t in model.index_files.items() if d in public_dirs}

    if args.check:
        findings.extend(check_findings(model, profile))
        if findings:
            _print_findings(findings)
            return 2
        print(f"ok - publish check passed: {len(model.public_ids())} public concept(s), no redaction rule matches")
        return 0

    assert out is not None
    findings.extend(out_findings(out, bundle, args.out))
    if findings:
        _print_findings(findings)
        return 2

    prepare_out(out)
    redacted_model, redacted_texts, redactions = redacted_copies(model, filtered, profile)
    render_site(redacted_model, redacted_texts, out)
    write_search(redacted_model, out, site_title(redacted_texts))

    public_count = len(model.public_ids())
    private_count = len(model.concepts) - public_count
    print(
        f"ok - published {public_count} public concept(s) to {args.out} "
        f"({private_count} private excluded, {redactions} redaction(s) applied)"
    )
    if public_count == 0:
        print(
            f"note - no public concepts: default visibility is private ({model.default_reason}); "
            "set x_visibility: public on concepts or x_visibility_default: public in schema.md"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
